#!/usr/bin/env python3
"""Generate additional synthetic reconciliation datasets deterministically.

Datasets: saas_billing_v1, telecom_v1, travel_v1.

Each dataset uses the same input field names as finance_v1
(bank_amount, ledger_amount, bank_reference, ledger_reference,
bank_date, ledger_date) so ForgeBench can run them without code changes.
Ground truth comes from explicit construction rules, never from a model.
Run with: python scripts/generate_more_datasets.py
"""

import json
import random
from datetime import date, timedelta
from decimal import Decimal
from pathlib import Path

SEED = 2026
REPO_ROOT = Path(__file__).resolve().parents[1]
DATASETS_ROOT = REPO_ROOT / "datasets"

FAMILIES = [
    "matched",
    "amount_mismatch",
    "date_mismatch",
    "reference_mismatch",
    "duplicate",
    "ambiguous",
]

LICENSE = "Proprietary - ForgeBench Commercial License (synthetic data generated by this repo)"
CREATED_ON = "2026-10-16"
SPLIT_SIZES = {"train": 42, "dev": 21, "test": 42}  # 105 total per dataset

FAMILY_RATIOS = {
    "train": {
        "matched": 0.25,
        "amount_mismatch": 0.20,
        "date_mismatch": 0.15,
        "reference_mismatch": 0.15,
        "duplicate": 0.125,
        "ambiguous": 0.125,
    },
    "dev": {
        "matched": 0.25,
        "amount_mismatch": 0.20,
        "date_mismatch": 0.15,
        "reference_mismatch": 0.15,
        "duplicate": 0.125,
        "ambiguous": 0.125,
    },
    "test": {
        "matched": 0.25,
        "amount_mismatch": 0.20,
        "date_mismatch": 0.1667,
        "reference_mismatch": 0.1667,
        "duplicate": 0.10,
        "ambiguous": 0.1166,
    },
}

DAYS = []
d = date(2026, 8, 17)
end = date(2026, 10, 30)
while d <= end:
    if d.weekday() < 5:
        DAYS.append(d)
    d += timedelta(days=1)


def money(rng: random.Random) -> str:
    whole = rng.choice([rng.randint(1, 950), rng.randint(1, 250), rng.randint(500, 9500)])
    cents = rng.choice([".00", ".00", ".50", ".99", ".37", ".15", ".80"])
    return f"${whole}{cents}"


def shift_day(day: date, delta: int) -> date:
    shifted = day + timedelta(days=delta)
    while shifted.weekday() >= 5:
        shifted += timedelta(days=1 if delta >= 0 else -1)
    return shifted


def typo_digit(rng: random.Random, text: str) -> str:
    digits = [i for i, ch in enumerate(text) if ch.isdigit() and ch != "0"]
    if not digits:
        return text
    position = rng.choice(digits)
    new_digit = rng.choice([c for c in "123456789" if c != text[position]])
    return text[:position] + new_digit + text[position + 1 :]


def base_fields(rng: random.Random, vendor: str, ref_prefix: str) -> dict[str, str]:
    amount = money(rng)
    reference = f"{ref_prefix}{rng.randint(1000, 9999)}"
    day = rng.choice(DAYS).isoformat()
    return {
        "vendor": vendor,
        "description": f"Invoice payment - {vendor}",
        "bank_amount": amount,
        "ledger_amount": amount,
        "bank_reference": reference,
        "ledger_reference": reference,
        "bank_date": day,
        "ledger_date": day,
    }


def build_cases(
    rng: random.Random, size: int, split: str, prefix: str, vendors: list[str], ref_prefix: str
) -> list[dict]:
    ratios = FAMILY_RATIOS[split]
    counts = {family: round(ratio * size) for family, ratio in ratios.items()}
    drift = size - sum(counts.values())
    if drift:
        biggest = max(counts, key=lambda family: counts[family])
        counts[biggest] += drift

    cases: list[dict] = []
    next_id = 1
    for family, count in counts.items():
        for _ in range(count):
            vendor = rng.choice(vendors)
            fields = base_fields(rng, vendor, ref_prefix)
            category = family
            requires_review = family != "matched"
            explanation = ""

            if family == "matched":
                if rng.random() < 0.1:  # refund-shaped edge case, still matched
                    fields["bank_amount"] = f"-{fields['bank_amount']}"
                    fields["ledger_amount"] = fields["bank_amount"]
                explanation = "Bank and ledger agree on amount, date and reference."

            elif family == "amount_mismatch":
                ledger = Decimal(fields["ledger_amount"].lstrip("$"))
                variant = next_id % 4
                if variant == 0:
                    bank = Decimal(typo_digit(rng, fields["ledger_amount"].lstrip("$")))
                elif variant == 1:
                    bank = ledger * 2
                elif variant == 2:
                    bank = ledger - Decimal(str(rng.choice(["2.50", "5.00", "12.75"])))
                else:
                    bank = (ledger / 2).quantize(Decimal("0.01"))
                fields["bank_amount"] = f"${bank}"
                explanation = (
                    f"Bank amount {fields['bank_amount']} does not equal "
                    f"ledger amount {fields['ledger_amount']}."
                )

            elif family == "date_mismatch":
                ledger_day = date.fromisoformat(fields["ledger_date"])
                fields["bank_date"] = shift_day(ledger_day, rng.choice([1, 1, 2, 3, 5])).isoformat()
                explanation = (
                    f"Bank date {fields['bank_date']} does not equal "
                    f"ledger date {fields['ledger_date']}; amounts agree."
                )

            elif family == "reference_mismatch":
                reference = fields["ledger_reference"]
                variant = next_id % 4
                if variant == 0:
                    fields["bank_reference"] = f"{reference}-A"
                elif variant == 1:
                    fields["bank_reference"] = typo_digit(rng, reference)
                elif variant == 2:
                    fields["bank_reference"] = reference.replace("SUB", "SUBSCRIPTION")
                else:
                    fields["bank_reference"] = reference.lower()
                explanation = (
                    f"Bank reference '{fields['bank_reference']}' does not equal "
                    f"ledger reference '{reference}'; amounts agree."
                )

            elif family == "duplicate":
                fields["bank_occurrences"] = "2"
                fields["ledger_occurrences"] = "1"
                explanation = "The bank shows the transaction twice while the ledger shows it once."

            else:  # ambiguous
                if next_id % 2 == 0:
                    fields["bank_reference"] = typo_digit(rng, fields["ledger_reference"])
                    fields["bank_date"] = shift_day(
                        date.fromisoformat(fields["ledger_date"]), 1
                    ).isoformat()
                    explanation = (
                        "Reference differs by one character and the bank posted "
                        "one day later; could be a corrected typo or a separate "
                        "invoice. Human review required."
                    )
                else:
                    fields["bank_occurrences"] = "2"
                    fields["ledger_occurrences"] = "2"
                    explanation = (
                        "The transaction pair appears twice on both sides; "
                        "duplicates or two legitimate orders with identical terms "
                        "cannot be told apart here."
                    )

            cases.append(
                {
                    "id": f"{prefix}-{next_id:04d}",
                    "task": "classification",
                    "input": fields,
                    "expected": {"category": category, "requires_review": requires_review},
                    "scenario_family": family,
                    "notes": None,
                    "reference_explanation": explanation,
                }
            )
            next_id += 1

    rng.shuffle(cases)
    return cases


def write_jsonl(path: Path, cases: list[dict]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as f:
        for c in cases:
            f.write(json.dumps(c) + "\n")


def write_card(
    out_dir: Path,
    name: str,
    task: str,
    total: int,
    split_sizes: dict[str, int],
    distribution: dict[str, int],
) -> None:
    lines = [
        f"# Dataset card: {name}",
        "",
        f"- **Name:** {name}  ",
        "- **Version:** 1.0.0  ",
        f"- **Task:** {task}  ",
        f"- **Created:** {CREATED_ON} (fully synthetic; no customer data)  ",
        f"- **Total cases:** {total}  ",
        f"- **License:** {LICENSE}",
        "",
        "## What is in it",
        "",
        "Each case shows one bank line item next to its ledger counterpart and asks:",
        "do these match, and if not, what kind of exception is it? Ground truth is",
        "produced by deterministic rules, never by a model.",
        "",
        "| Family | Ground truth |",
        "| --- | --- |",
        "| matched | amounts, dates and references agree |",
        "| amount_mismatch | amounts differ (takes precedence when other fields also differ) |",
        "| date_mismatch | dates differ, amounts agree |",
        "| reference_mismatch | references differ, amounts agree |",
        "| duplicate | one side shows more occurrences than the other |",
        "| ambiguous | conflicting weak signals; must be escalated to a human |",
        "",
        "## Splits",
        "",
        "| Split | Cases |",
        "| --- | ---: |",
    ]
    lines += [f"| {split} | {size} |" for split, size in split_sizes.items()]
    lines += [
        "",
        "## Class distribution (all splits)",
        "",
        "| Category | Cases |",
        "| --- | ---: |",
    ]
    lines += [f"| {cat} | {count} |" for cat, count in sorted(distribution.items())]
    lines += [
        "",
        "## Intended use",
        "",
        "- Comparing prompts and structured-output strategies on one fixed, versioned",
        "  test set.",
        "- Validating an evaluation pipeline end to end without any API key.",
        "",
        "## Out-of-scope uses and limitations",
        "",
        "- The data is synthetic and does not encode real operations messiness;",
        "  strong results here do not imply production readiness.",
        "- 'ambiguous' encodes one specific kind of undecidability. Treat",
        "  escalation metrics as a lower bound.",
        "- Do not use this dataset to compare models that were trained on it.",
    ]
    (out_dir / "dataset_card.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    specs = [
        {
            "name": "saas_billing_v1",
            "task": "saas_subscription_billing_reconciliation",
            "prefix": "SB",
            "vendors": [
                "Stripe",
                "Salesforce",
                "HubSpot",
                "Zoom",
                "Slack",
                "Notion",
                "Figma",
                "Atlassian",
                "Dropbox",
                "Adobe",
                "Microsoft 365",
                "Google Workspace",
                "AWS",
                "Snowflake",
                "Datadog",
            ],
            "ref_prefix": "SUB-",
        },
        {
            "name": "telecom_v1",
            "task": "telecom_billing_reconciliation",
            "prefix": "TC",
            "vendors": [
                "Verizon",
                "AT&T",
                "T-Mobile",
                "Comcast",
                "Cox",
                "Spectrum",
                "Vodafone",
                "Orange",
                "Telefónica",
                "BT Group",
            ],
            "ref_prefix": "ACCT-",
        },
        {
            "name": "travel_v1",
            "task": "travel_expense_reconciliation",
            "prefix": "TR",
            "vendors": [
                "Delta",
                "United",
                "American Airlines",
                "Marriott",
                "Hilton",
                "Hyatt",
                "Expedia",
                "Booking.com",
                "Airbnb",
                "Hertz",
            ],
            "ref_prefix": "CONF-",
        },
    ]

    random.Random(SEED)
    for spec in specs:
        name = spec["name"]
        out_dir = DATASETS_ROOT / name
        out_dir.mkdir(parents=True, exist_ok=True)

        distribution: dict[str, int] = {}
        next_global_id = 1
        all_cases: list[dict] = []

        for split, size in SPLIT_SIZES.items():
            # Re-seed per dataset+split so output is deterministic and stable.
            split_rng = random.Random(f"{SEED}-{name}-{split}")
            records = build_cases(
                split_rng, size, split, spec["prefix"], spec["vendors"], spec["ref_prefix"]
            )
            # Re-number ids sequentially across the whole dataset.
            for record in records:
                record["id"] = f"{spec['prefix']}-{next_global_id:04d}"
                next_global_id += 1
            lines = []
            for record in records:
                dist_cat = record["expected"]["category"]
                distribution[dist_cat] = distribution.get(dist_cat, 0) + 1
                lines.append(json.dumps(record))
            (out_dir / f"{split}.jsonl").write_text("\n".join(lines) + "\n", encoding="utf-8")
            all_cases.extend(records)
            print(f"wrote {out_dir / f'{split}.jsonl'} ({len(records)} cases)")

        meta = {
            "name": name,
            "version": "1.0.0",
            "task": spec["task"],
            "license": LICENSE,
            "created_on": CREATED_ON,
            "families": FAMILIES,
            "splits": {
                split: {"file": f"{split}.jsonl", "n": size} for split, size in SPLIT_SIZES.items()
            },
            "generator": {
                "script": "scripts/generate_more_datasets.py",
                "seed": SEED,
                "note": "Ground truth from deterministic rules; no model involved.",
            },
        }
        (out_dir / "dataset.json").write_text(json.dumps(meta, indent=2) + "\n", encoding="utf-8")
        write_card(
            out_dir, name, spec["task"], sum(SPLIT_SIZES.values()), SPLIT_SIZES, distribution
        )
        print(f"wrote {out_dir / 'dataset.json'} and dataset_card.md")
        print(f"class distribution: {dict(sorted(distribution.items()))}")


if __name__ == "__main__":
    main()
